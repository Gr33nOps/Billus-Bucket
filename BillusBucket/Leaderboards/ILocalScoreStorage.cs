    /// <summary>
    /// Abstraction for saving the player's personal-best score, custom player name,
    /// and cross-device Save/Connect Code locally.
    /// Desktop uses LeaderboardStore + profile files on disk; Browser uses safe localStorage with in-memory fallback.
    /// </summary>
    public interface ILocalScoreStorage
    {
        bool IsPersistentStorageAvailable { get; }
        bool HasCustomDisplayName { get; }
        bool HasPendingProfileSync => false;
        void SetPendingProfileSync(bool pending) { }
        BigInteger LoadPersonalBest();
        void SavePersonalBest(BigInteger bestScore, bool flushImmediately = true);
        string GetOrCreateAnonymousPlayerId();
        string GetOrCreateConnectCode();
        string GetOrCreateSafeDisplayName();
        void SaveCustomDisplayName(string customName);
        void ApplyRestoredProfile(string formattedConnectCode, string customDisplayName, BigInteger restoredPersonalBest);
        void Flush();
    }

    /// <summary>
    /// Pure in-memory storage used for automated tests and when browser storage is completely blocked.
    /// </summary>
    public sealed class InMemoryScoreStorage : ILocalScoreStorage
    {
        private BigInteger personalBest;
        private string playerId;
        private string connectCode;
        private string displayName;
        private bool hasCustomDisplayName;
        public bool HasPendingProfileSync { get; private set; }
        public void SetPendingProfileSync(bool pending) => HasPendingProfileSync = pending;

        public bool IsPersistentStorageAvailable { get; }
        public bool HasCustomDisplayName => hasCustomDisplayName;

        public InMemoryScoreStorage(BigInteger initialBest = default, bool reportPersistentAvailable = true)
        {
            personalBest = initialBest < BigInteger.Zero ? BigInteger.Zero : initialBest;
            IsPersistentStorageAvailable = reportPersistentAvailable;
        }

        public BigInteger LoadPersonalBest()
        {
            return personalBest;
        }

        public void SavePersonalBest(BigInteger bestScore, bool flushImmediately = true)
        {
            if (bestScore > personalBest)
            {
                personalBest = bestScore;
            }
        }

        public string GetOrCreateAnonymousPlayerId()
        {
            if (string.IsNullOrWhiteSpace(playerId))
            {
                playerId = PlayerIdentityValidator.CreateConnectCode();
                if (string.IsNullOrWhiteSpace(connectCode))
                {
                    connectCode = playerId;
                }
            }

            return playerId;
        }

        public string GetOrCreateConnectCode()
        {
            if (!string.IsNullOrWhiteSpace(connectCode))
            {
                return connectCode;
            }

            string id = GetOrCreateAnonymousPlayerId();
            if (PlayerIdentityValidator.TryNormalizeConnectCode(id, out string formatted))
            {
                connectCode = formatted;
            }
            else
            {
                connectCode = PlayerIdentityValidator.CreateConnectCode();
            }

            return connectCode;
        }

        public string GetOrCreateSafeDisplayName()
        {
            if (string.IsNullOrWhiteSpace(displayName))
            {
                displayName = AnonymousPlayerIdentity.CreateSafeDisplayName(GetOrCreateAnonymousPlayerId());
            }

            return displayName;
        }

        public void SaveCustomDisplayName(string customName)
        {
            if (PlayerIdentityValidator.TryValidateCustomName(customName, out string validName, out _))
            {
                displayName = validName;
                hasCustomDisplayName = true;
            }
        }

        public void ApplyRestoredProfile(string formattedConnectCode, string customDisplayName, BigInteger restoredPersonalBest)
        {
            if (PlayerIdentityValidator.TryNormalizeConnectCode(formattedConnectCode, out string normalizedCode))
            {
                playerId = normalizedCode;
                connectCode = normalizedCode;
            }

            if (PlayerIdentityValidator.TryValidateCustomName(customDisplayName, out string validName, out _))
            {
                displayName = validName;
                hasCustomDisplayName = !AnonymousPlayerIdentity.IsAutoGeneratedName(validName);
            }
            else if (!string.IsNullOrWhiteSpace(customDisplayName))
            {
                displayName = LeaderboardStore.NormalizeName(customDisplayName);
            }

            personalBest = BigInteger.Max(BigInteger.Zero, restoredPersonalBest);
        }

        public void Flush()
        {
        }
    }

    /// <summary>
    /// Desktop adapter wrapping the atomic-write LeaderboardStore JSON file plus local identity/profile files.
    /// </summary>
    public sealed class DesktopScoreStorage : ILocalScoreStorage
    {
        private const string PlayerSlotName = "PLAYER";
        private const string IdentityFileName = "player-id.txt";
        private const string ConnectCodeFileName = "connect-code.txt";
        private const string CustomNameFileName = "player-name.txt";

        private readonly LeaderboardStore store;
        private readonly string identityFilePath;
        private readonly string connectCodeFilePath;
        private readonly string customNameFilePath;
        private string cachedPlayerId;
        private string cachedConnectCode;
        private string cachedDisplayName;
        private bool hasCustomNameLoaded;
        private bool hasCustomDisplayName;

        private BigInteger? activeProfileBest;
        private string ActiveProfileBestPath => string.IsNullOrWhiteSpace(customNameFilePath) ? null : customNameFilePath + ".best";
        private bool pendingProfileSync;
        private string PendingProfilePath => string.IsNullOrWhiteSpace(customNameFilePath) ? null : customNameFilePath + ".pending";
        public bool HasPendingProfileSync => pendingProfileSync || TryReadFileText(PendingProfilePath) == "1";
        public void SetPendingProfileSync(bool pending)
        {
            pendingProfileSync = pending;
            TryWriteFileText(PendingProfilePath, pending ? "1" : "0");
        }

        public bool IsPersistentStorageAvailable => store.LastSaveError == null;

        public bool HasCustomDisplayName
        {
            get
            {
                EnsureCustomNameLoaded();
                return hasCustomDisplayName;
            }
        }

        public DesktopScoreStorage(LeaderboardStore store, string identityDirectory = null)
        {
            this.store = store ?? throw new ArgumentNullException(nameof(store));
            if (!string.IsNullOrWhiteSpace(identityDirectory))
            {
                identityFilePath = System.IO.Path.Combine(identityDirectory, IdentityFileName);
                connectCodeFilePath = System.IO.Path.Combine(identityDirectory, ConnectCodeFileName);
                customNameFilePath = System.IO.Path.Combine(identityDirectory, CustomNameFileName);
            }
        }

        public BigInteger LoadPersonalBest()
        {
            if (!activeProfileBest.HasValue && BigInteger.TryParse(TryReadFileText(ActiveProfileBestPath),
                    NumberStyles.Integer, CultureInfo.InvariantCulture, out BigInteger savedBest) && savedBest >= BigInteger.Zero)
                activeProfileBest = savedBest;
            if (activeProfileBest.HasValue) return activeProfileBest.Value;
            BigInteger best = store.BestFor(PlayerSlotName);
            EnsureCustomNameLoaded();
            if (hasCustomDisplayName && !string.IsNullOrWhiteSpace(cachedDisplayName))
            {
                best = BigInteger.Max(best, store.BestFor(cachedDisplayName));
            }

            return best;
        }

        public void SavePersonalBest(BigInteger bestScore, bool flushImmediately = true)
        {
            if (activeProfileBest.HasValue)
            {
                activeProfileBest = BigInteger.Max(activeProfileBest.Value, bestScore);
                TryWriteFileText(ActiveProfileBestPath, activeProfileBest.Value.ToString(CultureInfo.InvariantCulture));
            }
            store.Record(PlayerSlotName, bestScore, saveImmediately: false);
            EnsureCustomNameLoaded();
            if (hasCustomDisplayName && !string.IsNullOrWhiteSpace(cachedDisplayName))
            {
                store.Record(cachedDisplayName, bestScore, saveImmediately: false);
            }

            if (flushImmediately)
            {
                store.Flush();
            }
        }

        public string GetOrCreateAnonymousPlayerId()
        {
            if (!string.IsNullOrWhiteSpace(cachedPlayerId))
            {
                return cachedPlayerId;
            }

            string existing = TryReadFileText(identityFilePath);
            if (!string.IsNullOrWhiteSpace(existing) && existing.Replace("-", string.Empty).Length >= 12)
            {
                cachedPlayerId = existing;
                return cachedPlayerId;
            }

            string created = PlayerIdentityValidator.CreateConnectCode();
            TryWriteFileText(identityFilePath, created);
            cachedPlayerId = created;
            return cachedPlayerId;
        }

        public string GetOrCreateConnectCode()
        {
            if (!string.IsNullOrWhiteSpace(cachedConnectCode))
            {
                return cachedConnectCode;
            }

            string existingCode = TryReadFileText(connectCodeFilePath);
            if (PlayerIdentityValidator.TryNormalizeConnectCode(existingCode, out string normalizedExisting))
            {
                cachedConnectCode = normalizedExisting;
                return cachedConnectCode;
            }

            string id = GetOrCreateAnonymousPlayerId();
            if (PlayerIdentityValidator.TryNormalizeConnectCode(id, out string normalizedFromId))
            {
                cachedConnectCode = normalizedFromId;
            }
            else
            {
                cachedConnectCode = PlayerIdentityValidator.CreateConnectCode();
            }

            TryWriteFileText(connectCodeFilePath, cachedConnectCode);
            return cachedConnectCode;
        }

        public string GetOrCreateSafeDisplayName()
        {
            EnsureCustomNameLoaded();
            if (!string.IsNullOrWhiteSpace(cachedDisplayName))
            {
                return cachedDisplayName;
            }

            cachedDisplayName = AnonymousPlayerIdentity.CreateSafeDisplayName(GetOrCreateAnonymousPlayerId());
            return cachedDisplayName;
        }

        public void SaveCustomDisplayName(string customName)
        {
            if (!PlayerIdentityValidator.TryValidateCustomName(customName, out string validName, out _))
            {
                return;
            }

            hasCustomNameLoaded = true;
            hasCustomDisplayName = true;
            cachedDisplayName = validName;
            TryWriteFileText(customNameFilePath, validName);

            BigInteger best = LoadPersonalBest();
            if (best > BigInteger.Zero)
            {
                store.Record(validName, best, saveImmediately: true);
            }
        }

        public void ApplyRestoredProfile(string formattedConnectCode, string customDisplayName, BigInteger restoredPersonalBest)
        {
            if (PlayerIdentityValidator.TryNormalizeConnectCode(formattedConnectCode, out string normalizedCode))
            {
                cachedPlayerId = normalizedCode;
                cachedConnectCode = normalizedCode;
                TryWriteFileText(identityFilePath, normalizedCode);
                TryWriteFileText(connectCodeFilePath, normalizedCode);
            }

            if (PlayerIdentityValidator.TryValidateCustomName(customDisplayName, out string validName, out _))
            {
                hasCustomNameLoaded = true;
                cachedDisplayName = validName;
                hasCustomDisplayName = !AnonymousPlayerIdentity.IsAutoGeneratedName(validName);
                TryWriteFileText(customNameFilePath, hasCustomDisplayName ? validName : "");
            }

            activeProfileBest = BigInteger.Max(BigInteger.Zero, restoredPersonalBest);
            TryWriteFileText(ActiveProfileBestPath, activeProfileBest.Value.ToString(CultureInfo.InvariantCulture));
        }

        public void Flush()
        {
            store.Flush();
        }

        private void EnsureCustomNameLoaded()
        {
            if (hasCustomNameLoaded)
            {
                return;
            }

            hasCustomNameLoaded = true;
            string savedName = TryReadFileText(customNameFilePath);
            if (PlayerIdentityValidator.TryValidateCustomName(savedName, out string validName, out _))
            {
                cachedDisplayName = validName;
                hasCustomDisplayName = true;
            }
        }

        private static string TryReadFileText(string path)
        {
            if (string.IsNullOrWhiteSpace(path))
            {
                return string.Empty;
            }

            try
            {
                if (System.IO.File.Exists(path))
                {
                    return System.IO.File.ReadAllText(path).Trim();
                }
            }
            catch
            {
            }

            return string.Empty;
        }

        private static void TryWriteFileText(string path, string content)
        {
            if (string.IsNullOrWhiteSpace(path))
            {
                return;
            }

            try
            {
                string directory = System.IO.Path.GetDirectoryName(path);
                if (!string.IsNullOrEmpty(directory))
                {
                    System.IO.Directory.CreateDirectory(directory);
                }

                System.IO.File.WriteAllText(path, content ?? string.Empty);
            }
            catch
            {
            }
        }
    }

    /// <summary>
    /// Validates user-chosen player names (with App Store / portal-safe profanity filtering)
    /// and generates unambiguous 12-character cross-device Save/Connect Codes (XXXX-XXXX-XXXX).
    /// </summary>
    public static class PlayerIdentityValidator
    {
        public const int MinNameLength = 2;
        public const int MaxNameLength = 12;
        public const int ConnectCodeLength = 12;

        // 32 unambiguous uppercase characters (excludes 0, 1, I, O to prevent typos across devices).
        private const string CodeAlphabet = "23456789ABCDEFGHJKLMNPQRSTUVWXYZ";

        private static readonly string[] BlockedNameSubstrings =
        {
            "FUCK", "SHIT", "BITCH", "CUNT", "DICK", "COCK", "PUSSY", "NIGG",
            "FAGG", "SLUT", "WHORE", "PENIS", "VAGIN", "PORN", "RAPE", "NAZI",
            "HITLER", "CHUT", "BHENCH", "MADARCH", "GANDU", "RANDI", "LUND", "BHOSD"
        };

        public static string CreateConnectCode()
        {
            Span<byte> randomBytes = stackalloc byte[ConnectCodeLength];
            RandomNumberGenerator.Fill(randomBytes);

            char[] chars = new char[14];
            int writeIndex = 0;
            for (int i = 0; i < ConnectCodeLength; i++)
            {
                if (i == 4 || i == 8)
                {
                    chars[writeIndex++] = '-';
                }

                chars[writeIndex++] = CodeAlphabet[randomBytes[i] & 31];
            }

            return new string(chars);
        }

        public static string StripConnectCodeCharacters(string rawInput)
        {
            if (string.IsNullOrWhiteSpace(rawInput))
            {
                return string.Empty;
            }

            StringBuilder sb = new StringBuilder(ConnectCodeLength);
            foreach (char rawChar in rawInput)
            {
                char c = char.ToUpperInvariant(rawChar);
                if ((c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9'))
                {
                    sb.Append(c);
                    if (sb.Length == ConnectCodeLength)
                    {
                        break;
                    }
                }
            }

            return sb.ToString();
        }

        public static string FormatPartialConnectCode(string rawInput)
        {
            string clean = StripConnectCodeCharacters(rawInput);
            if (clean.Length <= 4)
            {
                return clean;
            }

            if (clean.Length <= 8)
            {
                return clean.Substring(0, 4) + "-" + clean.Substring(4);
            }

            return clean.Substring(0, 4) + "-" + clean.Substring(4, 4) + "-" + clean.Substring(8);
        }

        public static bool TryNormalizeConnectCode(string rawInput, out string formattedCode)
        {
            formattedCode = string.Empty;
            string clean = StripConnectCodeCharacters(rawInput);
            if (clean.Length != ConnectCodeLength)
            {
                return false;
            }

            formattedCode = clean.Substring(0, 4) + "-" + clean.Substring(4, 4) + "-" + clean.Substring(8, 4);
            return true;
        }

        public static bool TryValidateCustomName(string rawInput, out string validName, out string errorMessage)
        {
            validName = string.Empty;
            if (string.IsNullOrWhiteSpace(rawInput))
            {
                errorMessage = "ENTER 2-12 LETTERS OR NUMBERS";
                return false;
            }

            StringBuilder cleaned = new StringBuilder(MaxNameLength);
            bool previousWasUnderscore = false;
            string trimmed = rawInput.Trim().ToUpperInvariant();

            foreach (char c in trimmed)
            {
                if (char.IsWhiteSpace(c))
                {
                    if (!previousWasUnderscore && cleaned.Length > 0)
                    {
                        cleaned.Append('_');
                        previousWasUnderscore = true;
                    }
                    continue;
                }

                previousWasUnderscore = false;
                bool isAlphaNum = (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9');
                if (!isAlphaNum && c != '_' && c != '-')
                {
                    errorMessage = "USE LETTERS, NUMBERS, _ OR -";
                    return false;
                }

                cleaned.Append(c);
            }

            string candidate = cleaned.ToString();
            if (candidate.Length < MinNameLength || candidate.Length > MaxNameLength)
            {
                errorMessage = "NAME MUST BE 2-12 CHARACTERS";
                return false;
            }

            char first = candidate[0];
            char last = candidate[candidate.Length - 1];
            bool firstOk = (first >= 'A' && first <= 'Z') || (first >= '0' && first <= '9');
            bool lastOk = (last >= 'A' && last <= 'Z') || (last >= '0' && last <= '9');
            if (!firstOk || !lastOk)
            {
                errorMessage = "START AND END WITH A-Z OR 0-9";
                return false;
            }

            string normalizedLeet = candidate
                .Replace("_", string.Empty)
                .Replace("-", string.Empty)
                .Replace('0', 'O')
                .Replace('1', 'I')
                .Replace('3', 'E')
                .Replace('4', 'A')
                .Replace('5', 'S');

            for (int i = 0; i < BlockedNameSubstrings.Length; i++)
            {
                string blocked = BlockedNameSubstrings[i];
                if (candidate.Contains(blocked, StringComparison.Ordinal) ||
                    normalizedLeet.Contains(blocked, StringComparison.Ordinal))
                {
                    errorMessage = "NAME NOT ALLOWED";
                    return false;
                }
            }

            validName = candidate;
            errorMessage = string.Empty;
            return true;
        }
    }

    /// <summary>
    /// Generates fallback display tags (e.g. GUEST_4821) before a player picks their custom name.
    /// </summary>
    public static class AnonymousPlayerIdentity
    {
        public static string CreateSafeDisplayName(string anonymousId)
        {
            string source = string.IsNullOrWhiteSpace(anonymousId) ? "0000" : anonymousId;
            uint hash = 2166136261u;
            for (int i = 0; i < source.Length; i++)
            {
                hash ^= source[i];
                hash *= 16777619u;
            }

            int suffix = (int)(hash % 9000u) + 1000;
            return "GUEST_" + suffix.ToString(CultureInfo.InvariantCulture);
        }

        public static bool IsAutoGeneratedName(string displayName)
        {
            if (string.IsNullOrWhiteSpace(displayName) || displayName.Length != 10)
            {
                return false;
            }

            if (!displayName.StartsWith("BILLU_", StringComparison.OrdinalIgnoreCase) &&
                !displayName.StartsWith("GUEST_", StringComparison.OrdinalIgnoreCase))
            {
                return false;
            }

            for (int i = 6; i < 10; i++)
            {
                if (displayName[i] < '0' || displayName[i] > '9')
                {
                    return false;
                }
            }

            return displayName[6] != '0';
        }
    }
